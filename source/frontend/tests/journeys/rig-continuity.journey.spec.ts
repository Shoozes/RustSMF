import { workspaceControl, selectWorkspace, showModernPanel } from '../helpers/modern-shell';
import { test, expect, downloadBytes, exportEvidence, reopenProject, selectBone, watchJourneyErrors } from '../helpers/product-journey';
import { SAMPLE_OBJ } from '../helpers/smoke-helpers';

import { expectAssetContinuity } from '../helpers/asset-evidence';

test('product journey prepares a static rig and preserves hierarchy and metadata through saved files', async ({ page }) => {
  test.setTimeout(60_000);
  const assertErrors = watchJourneyErrors(page);
  await page.goto('/');
  await page.getByTestId('model-file-input').setInputFiles(SAMPLE_OBJ);
  await expect(page.getByTestId('status-text')).toContainText(/Loaded/i, { timeout: 15_000 });
  await selectWorkspace(page, 'rig');
  await showModernPanel(page, 'properties');
  await expect(page.getByTestId('rig-bone-count')).toHaveText('0');
  await (await workspaceControl(page, 'rig-prepare-root-skeleton')).click();
  await expect(page.getByTestId('rig-bone-count')).toHaveText('1');
  await selectBone(page, 'Root');
  await expect(page.getByTestId('rig-primary-axis')).toHaveValue('y');
  await (await workspaceControl(page, 'rig-primary-axis')).selectOption('x');
  await (await workspaceControl(page, 'rig-lock-toggle')).check();
  await (await workspaceControl(page, 'rig-rename-input')).fill('JourneyRoot');
  await (await workspaceControl(page, 'rig-rename-btn')).click();
  await expect(page.getByTestId('inspector-selected')).toHaveText('JourneyRoot');
  await expect(page.getByTestId('rig-primary-axis')).toHaveValue('x');
  await expect(page.getByTestId('rig-lock-toggle')).toBeChecked();
  await page.getByTestId('editor-undo-btn').click();
  await expect(page.getByTestId('inspector-selected')).toHaveText('Root');
  await expect(page.getByTestId('rig-primary-axis')).toHaveValue('x');
  await page.getByTestId('editor-redo-btn').click();
  await (await workspaceControl(page, 'rig-create-child-input')).fill('JourneyTip');
  await (await workspaceControl(page, 'rig-create-child-btn')).click();
  await expect(page.getByTestId('rig-bone-count')).toHaveText('2');
  await selectBone(page, 'JourneyTip');
  await (await workspaceControl(page, 'rig-primary-axis')).selectOption('z');
  await (await workspaceControl(page, 'rig-lock-toggle')).check();
  await (await workspaceControl(page, 'rig-pin-toggle')).check();
  const metadata = await downloadBytes(page, 'rig-save-metadata');
  expect(JSON.parse(metadata.toString()).bones.JourneyTip).toEqual({ primaryAxis: 'z', locked: true, pinned: true });
  await (await workspaceControl(page, 'rig-clear-metadata')).click();
  await expect(page.getByTestId('rig-primary-axis')).toHaveValue('y');
  await expect(page.getByTestId('rig-lock-toggle')).not.toBeChecked();
  await expect(page.getByTestId('rig-pin-toggle')).not.toBeChecked();
  await (await workspaceControl(page, 'rig-load-metadata')).setInputFiles({ name: 'journey.rig.json', mimeType: 'application/json', buffer: metadata });
  await expect(page.getByTestId('rig-primary-axis')).toHaveValue('z');
  await expect(page.getByTestId('rig-lock-toggle')).toBeChecked();
  await expect(page.getByTestId('rig-pin-toggle')).toBeChecked();
  await selectBone(page, 'JourneyRoot');
  await (await workspaceControl(page, 'rig-create-child-input')).fill('SecondBranch');
  await (await workspaceControl(page, 'rig-create-child-btn')).click();
  await selectBone(page, 'JourneyTip');
  await (await workspaceControl(page, 'rig-reparent-parent')).selectOption('SecondBranch');
  await (await workspaceControl(page, 'rig-reparent-btn')).click();
  expect((await exportEvidence(page)).hierarchy).toContainEqual({ name: 'JourneyTip', parent: 'SecondBranch' });
  await (await workspaceControl(page, 'bone-tree-item-SecondBranch')).focus();
  await (await workspaceControl(page, 'bone-tree-item-SecondBranch')).press('ArrowRight');
  await (await workspaceControl(page, 'rig-detach-toggle-btn')).click();
  await expect(page.getByTestId('bone-tree-item-JourneyTip')).toHaveAttribute('data-rig-bone-detached', 'true');
  await (await workspaceControl(page, 'rig-detach-toggle-btn')).click();
  await expect(page.getByTestId('bone-tree-item-JourneyTip')).toHaveAttribute('data-rig-bone-detached', 'false');
  await (await workspaceControl(page, 'rig-reparent-parent')).selectOption('JourneyRoot');
  await (await workspaceControl(page, 'rig-reparent-btn')).click();
  await selectBone(page, 'SecondBranch');
  await (await workspaceControl(page, 'rig-delete-bone-btn')).click();
  await expect(page.getByTestId('rig-bone-count')).toHaveText('2');
  const unspun = await exportEvidence(page);
  await (await workspaceControl(page, 'rig-spin-y-btn')).click();
  const spun = await exportEvidence(page);
  expect(spun.poses.find(p => p.name === 'JourneyRoot')!.rotation).not.toEqual(unspun.poses.find(p => p.name === 'JourneyRoot')!.rotation);
  await page.getByTestId('editor-undo-btn').click();
  expectAssetContinuity(await exportEvidence(page), unspun);
  await selectBone(page, 'JourneyTip');
  const before = await exportEvidence(page);
  expect(before.joints).toEqual(['JourneyRoot', 'JourneyTip']);
  expect(before.hierarchy).toEqual([{ name: 'JourneyRoot', parent: null }, { name: 'JourneyTip', parent: 'JourneyRoot' }]);
  expect(before.primitives[0].attributes.WEIGHTS_0.filter((_, i) => i % 4 === 0).every(w => w === 1)).toBe(true);
  const project = await downloadBytes(page, 'save-project-btn');
  const state = JSON.parse(project.toString()).state;
  expect(state.selected).toBe('JourneyTip');
  expect(state.rigMetadata.bones.JourneyTip).toEqual({ primaryAxis: 'z', locked: true, pinned: true });
  expect(state.rigMetadata.bones.JourneyRoot).toEqual({ primaryAxis: 'x', locked: true, pinned: false });
  expect(state.rigMetadata.bones).not.toHaveProperty('SecondBranch');
  expect(state.rigMetadata.bones).not.toHaveProperty('Root');
  await reopenProject(page, project);
  await selectWorkspace(page, 'rig');
  await selectBone(page, 'JourneyTip');
  await expect(page.getByTestId('rig-lock-toggle')).toBeChecked();
  await expect(page.getByTestId('rig-pin-toggle')).toBeChecked();
  expectAssetContinuity(await exportEvidence(page), before);
  await (await workspaceControl(page, 'rig-delete-bone-btn')).click();
  await expect(page.getByTestId('rig-bone-count')).toHaveText('1');
  await page.getByTestId('editor-undo-btn').click();
  await expect(page.getByTestId('rig-bone-count')).toHaveText('2');
  const smf = await downloadBytes(page, 'export-smf-btn', true);
  await page.getByTestId('model-file-input').setInputFiles({ name: 'prepared.smf', mimeType: 'application/octet-stream', buffer: smf });
  await page.getByTestId('confirm-model-replacement').click();
  await expect(page.getByTestId('status-text')).toContainText('prepared.smf', { timeout: 15_000 });
  const converted = await exportEvidence(page);
  expect(converted.joints).toHaveLength(2);
  expect(converted.primitives[0].attributes.POSITION.length).toBe(before.primitives[0].attributes.POSITION.length);
  assertErrors();
});
