import { test, expect, downloadBytes, exportEvidence, pauseJourney, reopenProject, selectBone, watchJourneyErrors } from '../helpers/product-journey';
import { createSkinnedGlbFixtureInputWithOptions } from '../helpers/skinned-glb-fixture';
import { selectWorkspace, showModernPanel  } from '../helpers/modern-shell';
import { dragRigIkTarget } from '../helpers/viewport-interactions';
import { setRangeValue } from '../helpers/timeline-interactions';
import { expectAssetContinuity, expectNumbersClose, expectMotion } from '../helpers/asset-evidence';

test('product journey cancels and bakes constrained IK, edits keys, and continues saved animation', async ({ page }) => {
  test.setTimeout(60_000);
  const assertErrors = watchJourneyErrors(page);
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.goto('/');
  await page.getByTestId('model-file-input').setInputFiles(await createSkinnedGlbFixtureInputWithOptions({ withHeadChain: true }));
  await expect(page.getByTestId('status-text')).toContainText(/Loaded:/, { timeout: 15_000 });
  await pauseJourney(page);
  await selectWorkspace(page, 'rig');
  await selectBone(page, 'FixtureRoot');
  await page.getByTestId('rig-lock-toggle').check();
  await page.getByTestId('rig-pin-toggle').check();
  await selectBone(page, 'FixtureTip');
  const tip = page.getByTestId('bone-tree-item-FixtureTip');
  await tip.locator('span').first().click();
  await selectBone(page, 'FixtureHead');
  await page.getByTestId('rig-tool-ik').click();
  await page.getByTestId('rig-ik-chain-length').selectOption('2');
  await page.getByTestId('rig-ik-pole-axis').selectOption('z');
  const rest = await exportEvidence(page);
  expect(await dragRigIkTarget(page, 'escape')).toBe(true);
  await expect(page.getByTestId('status-text')).toContainText(/Canceled IK pose.*restored the full chain/);
  const canceled = await exportEvidence(page);
  for (const bone of ['FixtureRoot', 'FixtureTip', 'FixtureHead']) {
    expectNumbersClose(canceled.poses.find(p => p.name === bone)!.rotation, rest.poses.find(p => p.name === bone)!.rotation);
  }
  expect(await dragRigIkTarget(page)).toBe(true);
  await expect(page.getByTestId('rig-ik-result')).toBeVisible();
  const posed = await exportEvidence(page);
  expectNumbersClose(posed.poses.find(p => p.name === 'FixtureRoot')!.rotation, rest.poses.find(p => p.name === 'FixtureRoot')!.rotation);
  expect(posed.poses.find(p => p.name === 'FixtureTip')!.rotation).not.toEqual(rest.poses.find(p => p.name === 'FixtureTip')!.rotation);
  await page.getByTestId('editor-undo-btn').click();
  expectNumbersClose((await exportEvidence(page)).poses.find(p => p.name === 'FixtureTip')!.rotation, rest.poses.find(p => p.name === 'FixtureTip')!.rotation);
  await page.getByTestId('editor-redo-btn').click();
  expectNumbersClose((await exportEvidence(page)).poses.find(p => p.name === 'FixtureTip')!.rotation, posed.poses.find(p => p.name === 'FixtureTip')!.rotation);
  // Undo/redo deliberately invalidates the old IK target; solve a fresh target before baking.
  expect(await dragRigIkTarget(page)).toBe(true);
  await expect(page.getByTestId('rig-ik-bake-btn')).toBeEnabled();
  await page.getByTestId('rig-ik-bake-btn').click();
  await expect(page.getByTestId('status-text')).toContainText(/bake|baked/i);
  await selectWorkspace(page, 'animate');
  await showModernPanel(page, 'properties');
  await selectBone(page, 'FixtureTip');
  await page.getByTestId('animation-lock-bone-btn').click();
  await expect(page.getByTestId('animation-lock-state')).toContainText(/locked/i);
  await page.getByTestId('animation-lock-bone-btn').click();
  await page.getByTestId('animation-scope-select').selectOption('branch');
  await setRangeValue(page, 'scrub-slider', 0.25);
  await page.getByTestId('transform-rot-btn').click();
  await page.getByTestId('animation-insert-key-btn').click();
  await page.getByTestId('animation-copy-key-btn').click();
  await setRangeValue(page, 'scrub-slider', 0.4);
  await page.getByTestId('animation-paste-key-btn').click();
  await expect(page.getByTestId('timeline-keyframe-lane')).toHaveAttribute('data-keyframe-count', /[3-9]\d*/);
  await page.getByTestId('animation-update-key-btn').click();
  await page.getByTestId('animation-delete-key-btn').click();
  await page.getByTestId('editor-undo-btn').click();
  await page.getByTestId('animation-duplicate-clip-btn').click();
  await page.getByTestId('animation-clip-name-input').fill('Journey IK');
  await page.getByTestId('animation-rename-clip-btn').click();
  await page.getByTestId('animation-retime-input').fill('1');
  await page.getByTestId('animation-loop-toggle').uncheck();
  await page.getByTestId('animation-interpolation-select').selectOption('quadratic');
  await expect(page.getByTestId('animation-interpolation-note')).toContainText(/linear/i);
  const authored = await exportEvidence(page);
  expect(authored.clips.map(c => c.name)).toEqual(['FixtureBend', 'Journey IK']);
  expect(authored.clips[1].duration).toBeCloseTo(1, 5);
  expectMotion(authored.clips[1]);
  const project = await downloadBytes(page, 'save-project-btn');
  await reopenProject(page, project);
  await pauseJourney(page);
  expectAssetContinuity(await exportEvidence(page), authored);
  await showModernPanel(page, 'properties');
  await page.getByTestId('animation-clip-name-input').fill('Continued IK');
  await page.getByTestId('animation-rename-clip-btn').click();
  await page.getByTestId('editor-undo-btn').click();
  await expect(page.getByTestId('animation-clip-name-input')).toHaveValue('Journey IK');
  assertErrors();
});
