import fs from 'node:fs';
import { test, expect } from '@playwright/test';
import { BLACK_CAT_PATH, expectCatContinuity } from '../helpers/black-cat-evidence';
import { downloadBytes, pauseJourney, renameSubmodel, reopenProject, watchJourneyErrors } from '../helpers/product-journey';
import { clickEditorHistory, selectWorkspace, workspaceControl } from '../helpers/modern-shell';
import { readAssetEvidence } from '../helpers/asset-evidence';

test('original Sable pack continues editing through project reopen and queued GLB roundtrip', async ({ page }) => {
  test.setTimeout(120000);
  const errors = watchJourneyErrors(page);
  await page.goto('/');
  const choosing = page.waitForEvent('filechooser');
  await page.getByTestId('open-model-btn').click();
  await (await choosing).setFiles(BLACK_CAT_PATH);
  await expect(page.getByTestId('status-text')).toHaveText('Loaded: sable.glb', { timeout: 15000 });
  await pauseJourney(page);
  await (await workspaceControl(page, 'clip-item-0')).press('Enter');
  await page.locator('[data-testid^="clip-item-"]').filter({ hasText: 'Sit (' }).click();
  await pauseJourney(page);
  await page.getByTestId('scrub-slider').press('End');
  await renameSubmodel(page, 'Sable_Pack');
  await expect.poll(async () => {
    const stored = await page.evaluate(() => localStorage.getItem('rustsmf.project.autosave.0'));
    return stored ? readAssetEvidence(Buffer.from(JSON.parse(stored).asset.bytesBase64, 'base64')).poses.some(node => node.name === 'Sable_Pack') : false;
  }, { timeout: 15000 }).toBe(true);
  await expect(page.getByTestId('error-banner')).toBeHidden();
  const project = await downloadBytes(page, 'save-project-btn');
  const saved = JSON.parse(project.toString());
  expect(saved.state).toMatchObject({ currentClipName: 'Sit', currentTime: 2, isPlaying: false });
  expectCatContinuity(Buffer.from(saved.asset.bytesBase64, 'base64'));
  await reopenProject(page, project);
  await selectWorkspace(page, 'animate');
  await expect(page.getByTestId('time-display')).toHaveText('2.00 / 2.00s');
  await renameSubmodel(page, 'Sable_Continued');
  await clickEditorHistory(page, 'undo');
  await selectWorkspace(page, 'view');
  await expect(page.getByTestId('outliner')).toContainText('Sable_Pack');
  await clickEditorHistory(page, 'redo');
  await selectWorkspace(page, 'view');
  await expect(page.getByTestId('outliner')).toContainText('Sable_Continued');
  await selectWorkspace(page, 'export');
  const queue = page.getByTestId('export-queue');
  await queue.locator('summary').first().click();
  await page.getByTestId('export-preset').selectOption('glb');
  await page.locator('.export-queue-options > summary').click();
  await page.getByTestId('export-queue-name').fill('sable-pack');
  await page.getByTestId('export-queue-animation').check();
  await page.getByTestId('export-queue-add').click();
  const pending = page.waitForEvent('download');
  await page.getByTestId('export-queue-run').click();
  const download = await pending;
  expect(download.suggestedFilename()).toBe('sable-pack.glb');
  await expect(page.getByTestId('export-queue-item')).toHaveAttribute('data-status', 'downloaded');
  const exported = fs.readFileSync((await download.path())!);
  expectCatContinuity(exported);
  const opening = page.waitForEvent('filechooser');
  await page.getByTestId('open-model-btn').click();
  await (await opening).setFiles({ name: 'sable-roundtrip.glb', mimeType: 'model/gltf-binary', buffer: exported });
  await page.getByTestId('confirm-model-replacement').click();
  await expect(page.getByTestId('status-text')).toHaveText('Loaded: sable-roundtrip.glb', { timeout: 15000 });
  await pauseJourney(page);
  const roundtrip = await downloadBytes(page, 'export-glb-btn', true);
  expectCatContinuity(roundtrip);
  await renameSubmodel(page, 'Sable_After_Roundtrip');
  await expect.poll(async () => {
    const stored = await page.evaluate(() => localStorage.getItem('rustsmf.project.autosave.0'));
    return stored ? readAssetEvidence(Buffer.from(JSON.parse(stored).asset.bytesBase64, 'base64')).poses.some(node => node.name === 'Sable_After_Roundtrip') : false;
  }, { timeout: 15000 }).toBe(true);
  await expect(page.getByTestId('error-banner')).toBeHidden();
  const recovery = JSON.parse((await page.evaluate(() => localStorage.getItem('rustsmf.project.autosave.0')))!);
  expectCatContinuity(Buffer.from(recovery.asset.bytesBase64, 'base64'));
  errors();
});
